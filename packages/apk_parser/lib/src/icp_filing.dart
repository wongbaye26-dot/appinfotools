import 'arsc/string_pool.dart';

/// 从 `resources.arsc` 的全局字符串池里找 **ICP 备案号**。
///
/// ## 为什么是「扫字符串池」而不是读某个字段
///
/// `AndroidManifest.xml` 里**没有**标准字段放备案号，各家应用把它写在各处
/// （关于页文案、应用名后缀、自定义 `meta-data`）。工信部 2023 年起要求应用
/// 在界面显著位置展示备案号，因此它几乎总会以**字符串字面量**的形式落在
/// `resources.arsc` 的字符串池里 —— 那是唯一一个「不依赖各家实现」的位置。
///
/// 实测（`抖音-v40.7.0.apk`）：字符串池里有一条独立的
/// `京ICP备16016397号-49A`，正是要抓的形态。而 `飞牛-v1.37.1.apk` 里一条都
/// 没有 —— 所以界面必须**取不到就不显示**，不能显示一个空的占位。
///
/// ## 边界
///
/// - **只覆盖字符串池**。写在 DEX 里的、或者运行时从服务端下发的备案号看不到
///   —— 这类应用会显示成「没有」。这是**已知局限**，不粉饰。
/// - **不做合规判定**。这里只回答「包里写了什么」，不回答「写的是不是真的」
///   「有没有过期」—— 那需要查工信部的库，不是静态解析能做的。
class IcpFilingScanner {
  IcpFilingScanner._();

  /// 省 / 自治区 / 直辖市的**简称**，简繁两种写法都收。
  ///
  /// 刻意逐个列出而不是写 `[\u4e00-\u9fa5]{0,1}`：后者在前一个汉字不是简称时
  /// 会把那个字一起吃进来 —— 实测 `备案ICP备2021000000号` 会匹配成
  /// `案ICP备2021000000号`。逐个列出既精确又自带文档。
  ///
  /// 收繁体写法是因为港澳台地区的应用会把备案号写成 `粵ICP證…號` ——
  /// 官方备案号用简体，但真实样本里两种都出现过。
  static const String provinceCodes = '京津冀晋蒙辽吉黑沪苏浙皖闽赣鲁豫鄂湘粤桂琼渝川贵云藏陕甘青宁新'
      '晉遼滬蘇閩贛魯粵瓊貴雲陝寧';

  /// 备案号的正则。
  ///
  /// 形态（工信部 2023 版备案号）：
  ///
  /// ```text
  /// 京 ICP 备 16016397 号 - 49A
  /// │  │   │  │        │  │
  /// │  │   │  │        │  └ 序号 + 可选字母（同一主体的第几个应用）
  /// │  │   │  │        └ 号
  /// │  │   │  └ 主体备案编号
  /// │  │   └ 备 / 證 / 证（"证"是经营性许可，格式相同）
  /// │  └ ICP
  /// └ 省份简称（可省：`ICP备2021000000号-1` 也合法）
  /// ```
  ///
  /// 空格容错只吃**半角与全角空格**，不用 `\s` —— 那会连换行一起吃掉，
  /// 让跨行的两段文字被拼成一个假的备案号。
  static final RegExp _pattern = RegExp(
    // 省份简称与 ICP 之间也可能有空格（`京 ICP 备…`）
    '(?:[$provinceCodes][ \u3000]?)?'
    // 备 / 備 / 證 / 证（「证」是经营性许可，格式相同）
    r'ICP[ \u3000]?[备備證证][ \u3000]?'
    // 主体编号：至少 5 位（老的经营许可证是 6 位、新备案是 8 位）
    r'\d{5,}'
    r'[ \u3000]?[号號]?'
    // 序号：-49A / -1 / -1234B（半角或全角连字符）
    r'(?:[ \u3000]?[-－][ \u3000]?\d{1,5}[A-Za-z]?)?',
  );

  /// 在 [pool] 里找出全部备案号（按出现顺序去重）。
  ///
  /// 返回空列表表示**没找到** —— 调用方据此决定「不显示这一行」，而不是显示
  /// 一个空值。
  static List<String> scan(StringPool? pool) {
    if (pool == null) return const [];
    return scanValues(pool.strings);
  }

  /// [scan] 的纯函数部分：只依赖一组字符串，不依赖 arsc。
  ///
  /// 单独拆出来是为了**可测** —— 造一个 `StringPool` 需要一份真实的
  /// `resources.arsc`，而这一段的正确性（哪些写法算备案号、哪些不算）恰恰
  /// 是最需要钉住的地方。
  static List<String> scanValues(Iterable<String> values) {
    final found = <String>[];
    final seen = <String>{};
    for (final raw in values) {
      // 先做一次极廉价的预筛：绝大多数字符串连 `ICP` 都不含，
      // 对它们跑正则（`抖音` 的字符串池有二十多万条）纯属浪费。
      if (!raw.contains('ICP')) continue;
      final match = _pattern.firstMatch(raw);
      if (match == null) continue;
      final value = match.group(0)!.trim();
      if (value.isEmpty) continue;
      if (seen.add(value)) found.add(value);
    }
    return found;
  }
}
