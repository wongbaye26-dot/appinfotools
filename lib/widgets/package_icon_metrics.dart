/// 应用图标的展示尺寸与圆角 —— **全应用只有这一份定义**。
///
/// 真实 App 图标是**圆角正方形**，圆角约为边长的 22.4%（iOS 图标的比例）。
/// 这个数字此前散在三处，各写各的：
///
/// | 位置 | 尺寸 | 圆角 |
/// |---|---|---|
/// | 概览页 Hero | 92 / 76（紧凑） | 边长 × 0.2237 |
/// | 分析页 Hero 卡片 | **72** | **16（固定像素）** |
/// | 版本对比槽位 | 48 | 边长 × 0.2237 |
///
/// 72 与 92 看起来差不多，但并排放就露馅 —— 用户的原话是「应用图标太小了
/// 一点，尺寸应该参考 HERO 区图标定义规则」。圆角那两处更糟：一个按比例、
/// 一个是固定 16px，改尺寸时圆角不会跟着变。
///
/// 因此这里给出**唯一的一份**：三处都从这里取，改一处三处一起变。
library;

class PackageIconMetrics {
  PackageIconMetrics._();

  /// 概览页 / 分析页 Hero 的图标边长。
  static const double heroSide = 92;

  /// 窄窗口（概览页紧凑模式）的 Hero 图标边长。
  static const double compactHeroSide = 76;

  /// 版本对比槽位的图标边长。
  static const double slotSide = 48;

  /// 圆角半径：边长的 22.4%。
  ///
  /// 用函数而不是常量：固定像素的圆角在尺寸变化时不会跟着变，那正是
  /// V2.4.8 之前分析页那个 72×72 + 16px 圆角的来历。
  static double radiusOf(double side) => side * 0.2237;
}
